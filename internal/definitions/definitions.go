// MetricType defines the type of Prometheus metric.
type MetricType string

// Supported metric types.
const (
	// TypeGauge represents a numerical gauge metric that can increase or decrease.
	TypeGauge MetricType = "gauge"
	// TypeCounter represents a monotonically increasing cumulative counter metric.
	TypeCounter MetricType = "counter"
	// TypeInfo represents a static informational metric with metadata labels and constant value 1.
	TypeInfo MetricType = "info"
)

// MetricDefinition describes a Prometheus metric with its type, unit, help text, and label schema.
type MetricDefinition struct {
	Type   MetricType
	Name   string
	Unit   string
	Help   string
	Labels []string
}

